// Demo location catalog shaped like Meta's Targeting Search
// (`GET /search?type=adgeolocation`) results. Region/city keys are
// placeholders — the live endpoint returns Meta's real numeric keys.
// Coordinates are approximate city centres, used for pins and the radius
// preview only.

const country = (code, en, ar, aliases = []) => ({ key: code, type: 'country', countryCode: code, name: { en, ar }, aliases })
const region = (code, slug, en, ar, aliases = []) => ({ key: `mock-region-${code}-${slug}`, type: 'region', countryCode: code, name: { en, ar }, aliases })
const city = (code, slug, en, ar, regionSlug, lat, lng, aliases = []) => ({
  key: `mock-city-${code}-${slug}`,
  type: 'city',
  countryCode: code,
  regionKey: `mock-region-${code}-${regionSlug}`,
  name: { en, ar },
  latitude: lat,
  longitude: lng,
  supportsRadius: true,
  aliases,
})
const area = (code, slug, en, ar, regionSlug, lat, lng, aliases = []) => ({
  ...city(code, slug, en, ar, regionSlug, lat, lng, aliases),
  key: `mock-neighborhood-${code}-${slug}`,
  type: 'neighborhood',
  supportsRadius: false,
})

